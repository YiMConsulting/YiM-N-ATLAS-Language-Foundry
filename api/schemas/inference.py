"""Inference schemas for control plane and playground gateway."""

from __future__ import annotations

from typing import Optional
from pydantic import BaseModel, Field, field_validator


class PlaygroundRequest(BaseModel):
    """
    Validated request payload for the developer playground.
    Enforces bounds and prevents empty/oversized requests.
    """

    prompt: str = Field(
        ...,
        description="Source English text to translate into Tiv.",
        max_length=4000,
    )
    language_code: Optional[str] = Field(
        default="tiv",
        description="Target language code (currently 'tiv' for Tiv pilot).",
    )
    experiment_id: Optional[str] = Field(
        default=None,
        description="Optional experiment identifier for provenance tracking.",
    )
    max_new_tokens: Optional[int] = Field(
        default=64,
        ge=1,
        le=256,
        description="Upper bound on generated tokens (strictly capped at 256).",
    )
    do_sample: Optional[bool] = Field(
        default=False,
        description="Whether to use stochastic sampling during generation.",
    )

    @field_validator("prompt")
    @classmethod
    def validate_non_empty_prompt(cls, value: str) -> str:
        if not value or not value.strip():
            raise ValueError("Input prompt cannot be empty or whitespace-only.")
        return value.strip()


class PlaygroundResponse(BaseModel):
    """
    Backward-compatible playground generation response.
    Preserves all fields expected by the frontend while including governance metadata.
    """

    generated_text: str = Field(description="Model generated translation text.")
    prompt: str = Field(description="Source English text provided by user.")
    rendered_prompt: Optional[str] = Field(
        default=None,
        description="Exact formatted instruction prompt sent to the base model.",
    )
    language_code: str = Field(default="tiv", description="Target language code.")
    model: str = Field(description="Model identifier (maps to base model for compatibility).")
    base_model: str = Field(description="Base model Hugging Face repository ID.")
    base_revision: str = Field(description="Pinned immutable commit SHA for base model.")
    adapter_repo: str = Field(description="LoRA adapter Hugging Face repository ID.")
    adapter_revision: str = Field(description="Pinned immutable commit SHA for LoRA adapter.")
    model_status: str = Field(
        default="smoke_test_preview",
        description="Governance status indicator.",
    )
    is_smoke_test_preview: bool = Field(
        default=True,
        description="Indicates that output is from an unvalidated smoke-test adapter.",
    )
    disclaimer: str = Field(description="Mandatory governance disclaimer.")
    latency_ms: float = Field(description="Round-trip inference execution latency in milliseconds.")
    experiment_id: Optional[str] = Field(
        default=None,
        description="Associated experiment ID if provided.",
    )


class InferenceStatusResponse(BaseModel):
    """
    Truthful status of the upstream inference service and configured revisions.
    Never fabricates model readiness if the upstream service is unreachable.
    """

    available: bool = Field(description="Whether the upstream inference service is reachable.")
    model_loaded: bool = Field(
        default=False,
        description="Whether the model weights are confirmed to be loaded in memory.",
    )
    message: Optional[str] = Field(
        default=None,
        description="Human-readable operational status or error detail.",
    )
    base_model: str = Field(
        default="NCAIR1/N-ATLaS",
        description="Configured base model repository ID.",
    )
    base_revision: str = Field(
        default="e294476928aca9030e924ca27bb8e085e8581273",
        description="Pinned base model commit SHA.",
    )
    adapter_repo: str = Field(
        default="YiMConsulting/n-atlas-tiv-lora-smoke-v1",
        description="Configured adapter repository ID.",
    )
    adapter_revision: str = Field(
        default="d413bebb74ef3b971eacdd62d6bc10e75654914a",
        description="Pinned adapter commit SHA.",
    )
    model_status: str = Field(
        default="smoke_test_preview",
        description="Configured model governance status.",
    )
    is_smoke_test_preview: bool = Field(
        default=True,
        description="Indicates unvalidated smoke-test preview.",
    )
    quality_validated: bool = Field(
        default=False,
        description="Explicit guarantee that quality is not validated.",
    )
    disclaimer: str = Field(
        default=(
            "This output was generated by the diagnostic smoke-test adapter (smoke_test_preview). "
            "It has NOT been translation-quality validated and must not be treated as production quality."
        ),
        description="Governance disclaimer.",
    )
    device: Optional[str] = Field(default=None, description="Upstream device setting.")
    torch_dtype: Optional[str] = Field(default=None, description="Upstream torch dtype setting.")
    quantization: Optional[str] = Field(default=None, description="Upstream quantization setting.")
