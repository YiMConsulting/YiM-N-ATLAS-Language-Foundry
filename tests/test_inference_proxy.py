    assert data["language_code"] == "tiv"
    assert data["model"] == "NCAIR1/N-ATLaS"
    assert "latency_ms" in data
    assert isinstance(data["latency_ms"], (int, float))

    # Governance & provenance fields
    assert data["rendered_prompt"] == UPSTREAM_SUCCESS_PAYLOAD["prompt"]
    assert data["base_model"] == "NCAIR1/N-ATLaS"
    assert data["base_revision"] == "e294476928aca9030e924ca27bb8e085e8581273"
    assert data["adapter_repo"] == "YiMConsulting/n-atlas-tiv-lora-smoke-v1"
    assert data["adapter_revision"] == "d413bebb74ef3b971eacdd62d6bc10e75654914a"
