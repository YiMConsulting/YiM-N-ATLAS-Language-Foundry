"use client";

import axios from "axios";
import { useEffect, useState } from "react";
import { useSearchParams } from "next/navigation";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import {
  foundryApi,
  type LanguageDto,
  type InferenceStatusResponse,
  type PlaygroundResponse,
} from "@/lib/api-client";
import { TivTranslationDemo } from "@/components/playground/tiv-translation-demo";

type SamplePrompt = {
  label: string;
  english: string;
  tivReference: string;
  notes: string;
};

const SAMPLE_PROMPTS: SamplePrompt[] = [
  {
    label: "Greeting",
    english: "Good morning.",
    tivReference: "Ngu dedoo.",
    notes: "Standard native greeting in everyday Tiv orthography.",
  },
  {
    label: "Market Location",
    english: "Where is the market?",
    tivReference: "Kasua ngu hana?",
    notes: "Authentic question particle and word order.",
  },
  {
    label: "Education",
    english: "The children are learning in school.",
    tivReference: "Mbayev mba henen kwagh ken makeranta.",
    notes: "Noun class marker (Mbayev) and loanword integration (makeranta).",
  },
  {
    label: "Hospitality",
    english: "Welcome to our home.",
    tivReference: "Msugh u va ken ya wase.",
    notes: "Traditional hospitality greeting formula.",
  },
];

export function Playground() {
  const searchParams = useSearchParams();
  const urlPrompt = searchParams.get("prompt");

  const [languages, setLanguages] = useState<LanguageDto[]>([]);
  const [selectedLanguageCode, setSelectedLanguageCode] = useState("tiv");
  const [inferenceStatus, setInferenceStatus] = useState<InferenceStatusResponse | null>(null);

  const [prevUrlPrompt, setPrevUrlPrompt] = useState(urlPrompt);
  const [prompt, setPrompt] = useState(urlPrompt || SAMPLE_PROMPTS[0].english);
  const [selectedSample, setSelectedSample] = useState<SamplePrompt | null>(
    urlPrompt ? null : SAMPLE_PROMPTS[0]
  );

  if (urlPrompt !== prevUrlPrompt) {
    setPrevUrlPrompt(urlPrompt);
    if (urlPrompt) {
      setPrompt(urlPrompt);
      setSelectedSample(null);
    }
  }

  const [isGenerating, setIsGenerating] = useState(false);
  const [generationOutput, setGenerationOutput] = useState<PlaygroundResponse | null>(null);
  const [errorStatus, setErrorStatus] = useState<{
    code: number;
    message: string;
  } | null>(null);

  // Advanced Controls
  const [showAdvanced, setShowAdvanced] = useState(false);
  const [maxNewTokens, setMaxNewTokens] = useState<number>(64);
  const [doSample, setDoSample] = useState<boolean>(false);

  // Fetch registered languages & live inference status on mount
  useEffect(() => {
    let active = true;

    async function loadTelemetry() {
      try {
        const [langRes, statusRes] = await Promise.allSettled([
          foundryApi.listLanguages(),
          foundryApi.getInferenceStatus(),
        ]);

        if (!active) return;

        if (langRes.status === "fulfilled") {
          setLanguages(langRes.value.items);
        }
        if (statusRes.status === "fulfilled") {
          setInferenceStatus(statusRes.value);
        } else {
          setInferenceStatus({
            available: false,
            model_loaded: false,
            message: "Upstream inference gateway is unreachable or offline.",
            base_model: "NCAIR1/N-ATLaS",
            base_revision: "e294476928aca9030e924ca27bb8e085e8581273",
            adapter_repo: "YiMConsulting/n-atlas-tiv-lora-smoke-v1",
            adapter_revision: "d413bebb74ef3b971eacdd62d6bc10e75654914a",
            model_status: "smoke_test_preview",
            is_smoke_test_preview: true,
            quality_validated: false,
            disclaimer:
              "This output was generated by the diagnostic smoke-test adapter (smoke_test_preview). It has NOT been translation-quality validated and must not be treated as production quality.",
          });
        }
      } catch {
        // Quiet failover
      }
    }

    loadTelemetry();

    return () => {
      active = false;
    };
  }, []);

  const handleSelectSample = (sample: SamplePrompt) => {
    setSelectedSample(sample);
    setPrompt(sample.english);
    setErrorStatus(null);
    setGenerationOutput(null);
  };

  const handleGenerate = async () => {
    const trimmed = prompt.trim();
    if (!trimmed) {
      toast.warning("Please enter a source prompt to test translation.");
      return;
    }

    if (trimmed.length > 4000) {
      toast.error("Prompt exceeds the 4,000 character maximum limit.");
      return;
    }

    setIsGenerating(true);
    setErrorStatus(null);
    setGenerationOutput(null);

    try {
      const res = await foundryApi.generate({
        prompt: trimmed,
        language_code: selectedLanguageCode,
        max_new_tokens: Math.min(256, Math.max(1, maxNewTokens)),
        do_sample: doSample,
      });

      if (res && typeof res.generated_text === "string") {
        setGenerationOutput(res);
        toast.success("Generation completed successfully.");
      } else {
        throw new Error("Invalid response format received from inference service.");
      }
    } catch (err: unknown) {
      if (axios.isAxiosError(err)) {
        const code = err.response?.status ?? 500;
        const detail = err.response?.data?.detail;
        const msg =
          typeof detail === "string"
            ? detail
            : code === 503
            ? "Inference worker is currently in standby / offline state. The platform strictly enforces truthfulness and never fabricates mock outputs."
            : err.message || "Inference request failed.";

        setErrorStatus({ code, message: msg });
        if (code === 503) {
          toast.info("Inference worker returned HTTP 503 (Expected offline standby status).");
        } else {
          toast.error(`Inference error (HTTP ${code}): ${msg}`);
        }
      } else {
        const msg = err instanceof Error ? err.message : "An unexpected error occurred.";
        setErrorStatus({ code: 500, message: msg });
        toast.error(msg);
      }
    } finally {
      setIsGenerating(false);
    }
  };

  const isTivPilot = selectedLanguageCode === "tiv";
  const charCount = prompt.length;

  return (
    <div className="space-y-8 max-w-4xl pb-16">
      {/* 1. Quiet Operational Bar */}
      <div className="flex flex-wrap items-center justify-between gap-3 text-xs text-foreground-secondary border-b border-border pb-4">
        <div className="flex items-center gap-3">
          <span className="font-medium text-foreground">
            {inferenceStatus?.base_model ?? "NCAIR1/N-ATLaS"}
          </span>
          <span className="text-foreground-muted">·</span>
          <span>
            LoRA: <span className="font-mono text-foreground">{inferenceStatus?.adapter_repo ?? "tiv-lora-smoke-v1"}</span>
          </span>
        </div>

        <div className="flex items-center gap-2">
          <span
            className={`inline-flex items-center gap-1.5 rounded-full px-2.5 py-0.5 text-[11px] font-medium ${
              inferenceStatus?.available
                ? "bg-accent-soft text-accent"
                : "bg-surface-secondary text-foreground-muted"
            }`}
          >
            <span
              className={`h-1.5 w-1.5 rounded-full ${
                inferenceStatus?.available ? "bg-accent" : "bg-warning"
              }`}
            />
            {inferenceStatus?.available ? "Inference Ready" : "Inference Standby"}
          </span>
          <span className="rounded-full bg-surface-secondary px-2.5 py-0.5 text-[11px] font-medium text-foreground-secondary">
            {inferenceStatus?.quality_validated ? "Validated" : "Diagnostic Preview"}
          </span>
        </div>
      </div>

      {/* 2. Language Selection & Presets */}
      <div className="space-y-3">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div className="flex items-center gap-2">
            <span className="text-xs font-medium text-foreground-muted">Target:</span>
            <select
              value={selectedLanguageCode}
              onChange={(e) => {
                setSelectedLanguageCode(e.target.value);
                setErrorStatus(null);
                setGenerationOutput(null);
              }}
              aria-label="Target language selection"
              className="rounded-md bg-surface-secondary px-2.5 py-1 text-xs font-medium text-foreground border border-border-subtle focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-accent"
            >
              {languages.length > 0 ? (
                languages.map((l) => (
                  <option key={l.code} value={l.code}>
                    {l.name} ({l.code}) {l.code.toLowerCase() === "tiv" ? "— Active Pilot" : ""}
                  </option>
                ))
              ) : (
                <option value="tiv">Tiv (tiv) — Active Pilot</option>
              )}
            </select>
            {!isTivPilot && (
              <span className="text-[11px] text-warning">
                Weights in discovery; Tiv is currently the active pilot.
              </span>
            )}
          </div>

          {/* Quick Ground-Truth Presets */}
          <div className="flex flex-wrap items-center gap-1.5">
            <span className="text-[11px] text-foreground-muted mr-1">Sample prompts:</span>
            {SAMPLE_PROMPTS.map((sample) => (
              <button
                key={sample.label}
                type="button"
                onClick={() => handleSelectSample(sample)}
                className={`rounded-full px-2.5 py-0.5 text-xs font-medium transition-colors cursor-pointer ${
                  selectedSample?.label === sample.label
                    ? "bg-accent text-accent-contrast font-semibold"
                    : "bg-surface-secondary text-foreground-secondary hover:text-foreground hover:bg-surface-tertiary"
                }`}
              >
                {sample.label}
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Tiv Experimental Translation Demo (Runtime Configured Gradio) */}
      {isTivPilot && <TivTranslationDemo />}

      {/* 3. Fluid Conversational Input Area */}
      <div className="space-y-3">
       

        
      </div>

      
    </div>
  );
}
