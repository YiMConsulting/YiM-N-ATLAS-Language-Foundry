"""FastAPI HTTP endpoints and health contract for N-ATLaS inference service."""

from __future__ import annotations

import logging
import os
from typing import Optional

from fastapi import Depends, FastAPI, HTTPException, Request, status
from fastapi.middleware.cors import CORSMiddleware

from inference_service.app.config import InferenceConfig
from inference_service.app.engine import ModelEngine
from inference_service.app.schemas import (
    GenerateRequest,
    GenerateResponse,
    HealthResponse,
    SmokeTestStatusResponse,
)

import re

logger = logging.getLogger("natlas.inference")

SMOKE_TEST_DISCLAIMER = (
    "This output was generated by the diagnostic smoke-test adapter (smoke_test_preview). "
    "It has NOT been translation-quality validated and must not be treated as production quality."
)


def _sanitize_error_detail(
    exc: Exception,
    configured_token: Optional[str] = None,
    configured_api_key: Optional[str] = None,
) -> str:
    """Scrub sensitive credentials, tokens, and authorization strings from errors."""
    msg = str(exc)
    if configured_token and configured_token in msg:
        msg = msg.replace(configured_token, "[REDACTED]")
    if configured_api_key and configured_api_key in msg:
        msg = msg.replace(configured_api_key, "[REDACTED]")
    msg = re.sub(r"hf_[a-zA-Z0-9_]{10,}", "[REDACTED]", msg)
    lower = msg.lower()
    if any(k in lower for k in ("token", "authorization", "bearer", "password", "secret")):
        return "Authentication failure or missing Hugging Face credentials."
    return msg


def verify_api_key(request: Request) -> None:
    """
    Validate INFERENCE_API_KEY authentication if configured.
    Accepts both 'Authorization: Bearer <key>' and 'X-API-Key: <key>' headers.
    If no API key is configured on the service, authentication is disabled.
    """
    config: InferenceConfig = request.app.state.config
    expected_key = config.api_key
    if not expected_key or not expected_key.strip():
        return

    expected_clean = expected_key.strip()

    # Check X-API-Key header
    x_api_key = request.headers.get("x-api-key")
    if x_api_key and x_api_key.strip() == expected_clean:
        return

    # Check Authorization: Bearer <key> header
    auth_header = request.headers.get("authorization")
    if auth_header:
        parts = auth_header.strip().split()
        if len(parts) == 2 and parts[0].lower() == "bearer" and parts[1] == expected_clean:
            return

    raise HTTPException(
        status_code=status.HTTP_401_UNAUTHORIZED,
        detail="Unauthorized: Invalid or missing API key.",
        headers={"WWW-Authenticate": "Bearer"},
    )


def get_engine(request: Request) -> ModelEngine:
    """Dependency provider for the application ModelEngine instance."""
    return request.app.state.engine


def create_app(
    engine: Optional[ModelEngine] = None,
    config: Optional[InferenceConfig] = None,
) -> FastAPI:
    """
    Application factory for the standalone N-ATLaS inference service.

    Guarantees:
    - Lazy model loading: Model weights are NEVER loaded during import or health checks.
    - Full transparency: Exposes model and adapter revisions, status, and disclaimer.
    - Provider neutrality: Standard ASGI app without cloud-specific bindings.
    """
    app_config = config or InferenceConfig()
    app_engine = engine or ModelEngine(config=app_config)

    app = FastAPI(
        title="N-ATLaS Inference Service",
        description=(
            "Standalone GPU inference microservice for N-ATLaS base model and "
            "Tiv LoRA smoke-test preview adapter."
        ),
        version="0.1.0",
    )

    # Attach shared engine to state
    app.state.engine = app_engine
    app.state.config = app_config

    # Configure CORS with explicit trusted origins
    allowed_origins = app_config.cors_origins
    is_wildcard = allowed_origins == ["*"]

    app.add_middleware(
        CORSMiddleware,
        allow_origins=allowed_origins if not is_wildcard else ["*"],
        allow_credentials=not is_wildcard,
        allow_methods=["GET", "POST", "OPTIONS"],
        allow_headers=["*"],
    )

    @app.get(
        "/health",
        response_model=HealthResponse,
        summary="Service Health and Liveness",
        tags=["System"],
    )
    def health_check(current_engine: ModelEngine = Depends(get_engine)) -> HealthResponse:
        """
        Report service availability truthfully without triggering model loading
        or falsely claiming the model is loaded/ready.
        """
        return HealthResponse(
            status="ok",
            model_loaded=current_engine.is_loaded,
            service="natlas-inference-service",
            version="0.1.0",
        )

    @app.get(
        "/v1/smoke-test/status",
        response_model=SmokeTestStatusResponse,
        summary="Model and Adapter Status",
        tags=["Inference"],
        dependencies=[Depends(verify_api_key)],
    )
    def smoke_test_status(current_engine: ModelEngine = Depends(get_engine)) -> SmokeTestStatusResponse:
        """
        Expose model initialization state, configured model and adapter revisions,
        and the smoke-test-only quality disclaimer.
        """
        cfg = current_engine.config
        return SmokeTestStatusResponse(
            model_loaded=current_engine.is_loaded,
            base_model=cfg.base_model,
            base_revision=cfg.base_revision,
            adapter_repo=cfg.adapter_repo,
            adapter_revision=cfg.adapter_revision,
            model_status=cfg.model_status,
            is_smoke_test_preview=True,
            quality_validated=False,
            disclaimer=SMOKE_TEST_DISCLAIMER,
            device=cfg.device,
            torch_dtype=cfg.torch_dtype,
            quantization=cfg.quantization,
        )

    @app.post(
        "/v1/generate",
        response_model=GenerateResponse,
        summary="Generate Tiv Translation",
        tags=["Inference"],
        dependencies=[Depends(verify_api_key)],
    )
    def generate_translation(
        request: GenerateRequest,
        current_engine: ModelEngine = Depends(get_engine),
    ) -> GenerateResponse:
        """
        Generate a Tiv translation for the supplied English input text.

        - Initializes the model lazily on first invocation.
        - Validates input and bounds max_new_tokens.
        - Returns truthful translation text and governance audit metadata.
        """
        # Lazy model loading
        if not current_engine.is_loaded:
            logger.info("First generation request received; triggering lazy model load.")
            try:
                current_engine.load_model()
            except Exception as exc:
                logger.error("Lazy model loading failed: %s", exc)
                safe_err = _sanitize_error_detail(
                    exc,
                    configured_token=current_engine.config.hf_token,
                    configured_api_key=current_engine.config.api_key,
                )
                raise HTTPException(
                    status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                    detail=f"Model engine initialization failed: {safe_err}",
                ) from None

        try:
            result = current_engine.generate(
                text=request.text,
                max_new_tokens=request.max_new_tokens,
            )
            return GenerateResponse(
                generated_text=result.generated_text,
                prompt=result.prompt,
                base_model=result.base_model,
                base_revision=result.base_revision,
                adapter_repo=result.adapter_repo,
                adapter_revision=result.adapter_revision,
                model_status=result.model_status,
                is_smoke_test_preview=result.is_smoke_test_preview,
                disclaimer=result.disclaimer,
                max_new_tokens=result.max_new_tokens,
            )
        except ValueError as exc:
            # Input validation error from engine
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=str(exc),
            ) from None
        except Exception as exc:
            logger.error("Generation execution failed: %s", exc)
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Inference generation failed during model execution.",
            ) from None

    return app


# Default ASGI application instance
app = create_app()
