def test_api_key_auth_enforced_when_configured(mock_engine, test_config):
    """When api_key is configured, requests without valid credentials return 401."""
    test_config.api_key = "secure_internal_gateway_token_123"
    app = create_app(engine=mock_engine, config=test_config)
    auth_client = TestClient(app)

    # Health check is public (unauthenticated) for orchestrator probes
    health_resp = auth_client.get("/health")
    assert health_resp.status_code == 200

    # Status check rejects missing auth
    status_no_auth = auth_client.get("/v1/smoke-test/status")
    assert status_no_auth.status_code == 401
    assert "Unauthorized" in status_no_auth.json()["detail"]

    # Status check rejects wrong auth
    status_bad_auth = auth_client.get(
        "/v1/smoke-test/status",
        headers={"Authorization": "Bearer wrong_token"},
    )
    assert status_bad_auth.status_code == 401

    # Status check accepts valid Bearer header
    status_valid_bearer = auth_client.get(
        "/v1/smoke-test/status",
        headers={"Authorization": f"Bearer {test_config.api_key}"},
    )
    assert status_valid_bearer.status_code == 200

    # Status check accepts valid X-API-Key header
    status_valid_x_key = auth_client.get(
        "/v1/smoke-test/status",
        headers={"X-API-Key": test_config.api_key},
    )
    assert status_valid_x_key.status_code == 200

    # Generate rejects missing auth
    gen_no_auth = auth_client.post("/v1/generate", json={"text": "Hello"})
    assert gen_no_auth.status_code == 401

    # Generate accepts valid Bearer header
    gen_valid_bearer = auth_client.post(
        "/v1/generate",
        json={"text": "Hello"},
        headers={"Authorization": f"Bearer {test_config.api_key}"},
    )
    assert gen_valid_bearer.status_code == 200

    # Generate accepts valid X-API-Key header
    gen_valid_x_key = auth_client.post(
        "/v1/generate",
        json={"text": "Hello"},
        headers={"X-API-Key": test_config.api_key},
    )
    assert gen_valid_x_key.status_code == 200


