def test_cors_preflight(client):
    """Ensure CORS options headers are handled correctly for trusted origins."""
    response = client.options(
        "/v1/generate",
        headers={
            "Origin": "http://localhost:3000",
            "Access-Control-Request-Method": "POST",
        },
    )
    assert response.status_code == 200
    assert response.headers.get("access-control-allow-origin") == "http://localhost:3000"


def test_cors_rejects_untrusted_origin(client):
    """CORS middleware does not reflect untrusted origins."""
    response = client.options(
        "/v1/generate",
        headers={
            "Origin": "http://evil-attacker.com",
            "Access-Control-Request-Method": "POST",
        },
    )
    # Untrusted origin must NOT receive allow header
    assert response.headers.get("access-control-allow-origin") != "http://evil-attacker.com"


