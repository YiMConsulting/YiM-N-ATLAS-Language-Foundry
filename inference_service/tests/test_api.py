def test_generate_rejects_empty_or_whitespace_input(client):
    """POST /v1/generate rejects empty or whitespace-only inputs with 422."""
    resp_empty = client.post("/v1/generate", json={"text": ""})
    assert resp_empty.status_code == 422

    resp_ws = client.post("/v1/generate", json={"text": "   \n\t  "})
    assert resp_ws.status_code == 422

    resp_missing = client.post("/v1/generate", json={})
    assert resp_missing.status_code == 422


def test_generate_rejects_invalid_tokens(client):
    """POST /v1/generate rejects non-positive or excessive token requests."""
    resp_zero = client.post("/v1/generate", json={"text": "Test", "max_new_tokens": 0})
    assert resp_zero.status_code == 422

    resp_neg = client.post("/v1/generate", json={"text": "Test", "max_new_tokens": -10})
    assert resp_neg.status_code == 422

    resp_too_high = client.post("/v1/generate", json={"text": "Test", "max_new_tokens": 5000})
    assert resp_too_high.status_code == 422


def test_generate_lazy_load_failure_masks_secrets(test_config):
    """When model loading fails, returns 503 without leaking secrets or raw tracebacks."""
    failing_engine = ModelEngine(config=test_config)
    failing_engine.load_model = MagicMock(
        side_effect=RuntimeError("Gated repo access failed token=hf_secret_super_private_token")
    )

    app = create_app(engine=failing_engine, config=test_config)
    failing_client = TestClient(app)

    response = failing_client.post("/v1/generate", json={"text": "Hello"})
    assert response.status_code == 503

    err_text = response.text
    # Secret token MUST NOT appear anywhere in HTTP response
    assert "hf_secret_super_private_token" not in err_text
    assert "Model engine initialization failed" in err_text


