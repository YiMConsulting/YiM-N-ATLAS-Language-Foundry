def test_health_endpoint_unloaded(client, mock_engine):
    """GET /health must report availability without triggering model loading."""
    assert not mock_engine.is_loaded

    response = client.get("/health")
    assert response.status_code == 200

    data = response.json()
    assert data["status"] == "ok"
    assert data["model_loaded"] is False
    assert data["service"] == "natlas-inference-service"
    assert data["version"] == "0.1.0"

    # Crucial guarantee: health check NEVER triggers load_model
    assert mock_engine.load_model.call_count == 0
    assert not mock_engine.is_loaded


