def test_generate_lazy_loads_model_and_returns_result(client, mock_engine, test_config):
    """POST /v1/generate triggers lazy loading on first request and returns output."""
    assert not mock_engine.is_loaded
    assert mock_engine.load_model.call_count == 0

    payload = {"text": "Good morning."}
    response = client.post("/v1/generate", json=payload)
    assert response.status_code == 200

    # Model was lazily loaded exactly once
    assert mock_engine.load_model.call_count == 1
    assert mock_engine.is_loaded

    data = response.json()
    assert data["generated_text"] == "M sugh u dedoo."
    assert "Translate the following English text into Tiv" in data["prompt"]
    assert data["base_model"] == test_config.base_model
    assert data["base_revision"] == test_config.base_revision
    assert data["adapter_repo"] == test_config.adapter_repo
    assert data["adapter_revision"] == test_config.adapter_revision
    assert data["model_status"] == "smoke_test_preview"
    assert data["is_smoke_test_preview"] is True
    assert "NOT been translation-quality validated" in data["disclaimer"]
    assert data["max_new_tokens"] == 48

    # Subsequent health check now truthfully reports model_loaded: true
    health_resp = client.get("/health")
    assert health_resp.status_code == 200
    assert health_resp.json()["model_loaded"] is True


